-- -----------------------------------------------------------------------------
-- 1. DATABASE SETUP
-- -----------------------------------------------------------------------------

-- Creating the Database
CREATE DATABASE [ASPOD ENTERPRISE]

-- Selecting the database to work with
USE [ASPOD ENTERPRISE]

-- Importing the retail sales dataset into SQL Server
-- The imported table is named Retail_Sales_Analysis

-- -----------------------------------------------------------------------------
-- 2. INITIAL DATA CHECK
-- -----------------------------------------------------------------------------

-- Checking the total number of records before data cleaning
SELECT COUNT(*) AS total_records
FROM Retail_Sales_Analysis

-- -----------------------------------------------------------------------------
-- 3. DATA CLEANING
-- -----------------------------------------------------------------------------

-- 3.1 Correcting the misspelled quantity column name
EXEC sp_rename
	'dbo.Retail_Sales_Analysis.quantiy', 
	'quantity',
	'COLUMN'

-- 3.2 Inspecting the dataset for missing values
SELECT * 
FROM Retail_Sales_Analysis
WHERE transactions_id IS NULL
	 OR sale_date IS NULL
	 OR sale_time IS NULL
	 OR customer_id IS NULL
	 OR gender IS NULL
	 OR age IS NULL
	 OR category IS NULL
	 OR quantity IS NULL
	 OR price_per_unit IS NULL
	 OR cogs IS NULL
	 OR total_sale IS NULL

-- 3.3 Calculating the average age of customers with recorded ages
SELECT AVG(age) AS average_age
FROM Retail_Sales_Analysis

-- 3.4 Replacing missing customer ages with recorded ages
UPDATE Retail_Sales_Analysis
SET age = (
          SELECT AVG(age) 
		  FROM Retail_Sales_Analysis
          )
WHERE age IS NULL

-- 3.5 Removing records with missing values in essential fields
DELETE FROM Retail_Sales_Analysis
WHERE transactions_id IS NULL
	 OR sale_date IS NULL
	 OR sale_time IS NULL
	 OR customer_id IS NULL
	 OR gender IS NULL
	 OR age IS NULL
	 OR category IS NULL
	 OR quantity IS NULL
	 OR price_per_unit IS NULL
	 OR cogs IS NULL
	 OR total_sale IS NULL

-- 3.6 Verifying the number of records remaining after cleaning
SELECT COUNT(*) AS cleaned_records
FROM Retail_Sales_Analysis

-- 3.7 Verifying if any customer ages are still missing
SELECT *
FROM Retail_Sales_Analysis
WHERE age IS NULL

-- 4. Data Exploration

-- 4.1 Measuring the total number of recorded sales transactions
SELECT 
     COUNT(transactions_id) as total_sales 
FROM Retail_Sales_Analysis

-- 4.2 Identifying the number of unique customers served
SELECT
     COUNT(DISTINCT customer_id) as distinct_customers
FROM Retail_Sales_Analysis

-- 4.3 Exploring the product categories available in the store
SELECT DISTINCT category
FROM Retail_Sales_Analysis

-- 4.4 Calculating the total revenue generated by the business
SELECT 
     SUM(total_sale) as total_revenue
FROM Retail_Sales_Analysis

-- -----------------------------------------------------------------------------
-- 5. Business Analysis
-- -----------------------------------------------------------------------------

-- 5.1 Checking sales made on November 5, 2022
SELECT * 
FROM Retail_Sales_Analysis
WHERE sale_date = '2022-11-05'

-- 5.2 Identifying clothing sales with four or more units in November 2022
SELECT *
FROM Retail_Sales_Analysis
WHERE category = 'Clothing'
      AND YEAR(sale_date) = '2022'
	  AND Month(sale_date) = '11'
	  AND quantity >= 4

-- 5.3 Comparing total revenue and number of order acrosss product categories
SELECT 
     category, 
	 SUM(total_sale) AS net_sales,
	 COUNT(*) AS total_order
FROM Retail_Sales_Analysis
GROUP BY category

-- 5.4 Examining the average age of customers purchasing Beauty products
SELECT
     category, 
	 AVG(age) AS average_age
FROM Retail_Sales_Analysis
WHERE category = 'Beauty'
GROUP BY category

-- 5.5 Identifying individual transactions generating more than 1,000 in sales
SELECT * 
FROM Retail_Sales_Analysis
WHERE total_sale > '1000'

-- 5.6 Comparing transaction volumes across genders and product categories
SELECT 
     category,
	 gender,
	 COUNT(*) AS total_transactions
FROM Retail_Sales_Analysis
GROUP BY category,
         gender
ORDER BY 1

-- 5.7 Identifying the month with the highest average transaction value in each year
SELECT
     Year,
	 Month,
	 Average_sale
FROM
(
SELECT YEAR(sale_date)  AS Year,
       MONTH(sale_date)  AS Month,
	   AVG(total_sale) AS Average_sale,
	   Rank() OVER(PARTITION BY YEAR(sale_date) ORDER BY  AVG(total_sale) DESC) AS Rank
FROM Retail_Sales_Analysis
GROUP BY 
       YEAR(sale_date),
	   MONTH(sale_date)
) AS T1
WHERE Rank = 1

-- 5.8 Identifying the five customers with the highest total sales
SELECT TOP 5
     customer_id,
	 SUM(total_sale) AS total_sales
FROM Retail_Sales_Analysis
GROUP BY customer_id
ORDER BY total_sales DESC

-- 5.9 Measuring the number of unique customers who purchased from each category
SELECT 
      category,
	  COUNT(DISTINCT customer_id) AS total_customers
FROM Retail_Sales_Analysis
GROUP BY category

-- 5.10 Counting orders made in the morning, afternoon, and evening
SELECT
     CASE
	     WHEN DATEPART(HOUR, sale_time) < 12 THEN 'Morning'
		 WHEN DATEPART(HOUR, sale_time) BETWEEN 12 AND 17 THEN 'Afternoon'
		 ELSE 'Evening'
      END AS TimeOfDay,
		 COUNT(*) No_Of_Orders
FROM Retail_Sales_Analysis
         GROUP BY 
	 CASE
	     WHEN DATEPART(HOUR, sale_time) < 12 THEN 'Morning'
		 WHEN DATEPART(HOUR, sale_time) BETWEEN 12 AND 17 THEN 'Afternoon'
		 ELSE 'Evening'
      END

